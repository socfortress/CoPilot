// Cloud security assessment with Prowler (#1328): a customer's cloud accounts, their scans and
// what they found. The shapes of backend/app/cloud_assessment/schema/cloud_assessment.py.

export type CloudProvider = "aws" | "azure" | "gcp" | "m365"
export type CloudAuthMethod = "role" | "access_keys" | "client_secret" | "service_account_key"
export type CloudSchedule = "off" | "daily" | "weekly"
export type CloudSeverity = "critical" | "high" | "medium" | "low" | "informational" | "unknown"
export type CloudScanStatus = "queued" | "starting" | "running" | "ingesting" | "completed" | "failed" | "cancelled"
export type CloudFindingStatus = "FAIL" | "MANUAL"
export type CloudCheckStatus = "fail" | "manual" | "pass" | "muted" | "no_findings"
export type CloudRequirementStatus = "pass" | "fail" | "manual" | "not_assessed"
export type CloudReportKind = "html" | "csv"

/** An account's settings: none of them secret. Which apply depends on the provider. */
export interface CloudAccountConfig {
	role_arn?: string
	/** An AWS role's External ID, generated by CoPilot: never sent back. */
	external_id?: string
	regions?: string[]
	tenant_id?: string
	client_id?: string
	subscription_ids?: string[]
	tenant_domain?: string
	project_ids?: string[]
	excluded_project_ids?: string[]
	organization_id?: string
	/** A GCP key's, filled in by CoPilot from the key file. */
	client_email?: string
	key_project_id?: string
	excluded_checks?: string[]
	excluded_services?: string[]
	timeout_seconds?: number
}

export interface CloudScanCounts {
	total: number
	passed: number
	failed: number
	manual: number
	muted: number
	failed_critical: number
	failed_high: number
	failed_medium: number
	failed_low: number
	failed_informational: number
	failed_unknown: number
	new_failed: number
	resolved_failed: number
}

export interface CloudAccountScanBrief {
	id: number
	status: CloudScanStatus
	trigger_type: "manual" | "schedule"
	queued_at: string | null
	completed_at: string | null
	counts: CloudScanCounts | null
	error_code: string | null
	/** As `CloudScan.previous_scan_id`. */
	previous_scan_id: number | null
}

export interface CloudAccount {
	id: number
	customer_code: string
	name: string
	provider: CloudProvider
	auth_method: CloudAuthMethod
	config: CloudAccountConfig
	/** AWS: the account in the role's ARN. Azure/Microsoft 365: the tenant. GCP: the key's project. */
	cloud_account: string | null
	external_id: string | null
	secret_configured: boolean
	secret_hint: string | null
	secret_expires_at: string | null
	secret_expires_in_days: number | null
	enabled: boolean
	schedule: CloudSchedule
	schedule_hour: number | null
	schedule_weekday: number | null
	next_scheduled_at: string | null
	last_connection_test_at: string | null
	last_connection_ok: boolean | null
	last_connection_error: string | null
	last_connection_message: string | null
	created_by: string | null
	created_at: string | null
	updated_by: string | null
	updated_at: string | null
	last_scan: CloudAccountScanBrief | null
	last_completed_scan: CloudAccountScanBrief | null
}

/** A GCP service-account key file, as downloaded. */
export type GcpServiceAccountKey = Record<string, unknown>

export interface CloudAccountSecret {
	access_key_id?: string
	secret_access_key?: string
	client_secret?: string
	service_account_key?: GcpServiceAccountKey
}

/** The settings an admin types; CoPilot fills in the External ID and a GCP key's details. */
export type CloudAccountConfigInput = Omit<CloudAccountConfig, "external_id" | "client_email" | "key_project_id">

export interface CloudAccountCreatePayload {
	name: string
	provider: CloudProvider
	auth_method: CloudAuthMethod
	config: CloudAccountConfigInput
	secret?: CloudAccountSecret | null
	secret_expires_at?: string | null
	enabled?: boolean
	schedule?: CloudSchedule
	schedule_hour?: number | null
	schedule_weekday?: number | null
}

/** Only the fields sent change. `config`, when sent, replaces every setting. */
export interface CloudAccountUpdatePayload {
	name?: string
	config?: CloudAccountConfigInput
	secret?: CloudAccountSecret | null
	remove_secret?: boolean
	secret_expires_at?: string | null
	enabled?: boolean
	schedule?: CloudSchedule
	schedule_hour?: number | null
	schedule_weekday?: number | null
}

export interface CloudScan {
	id: number
	account_id: number
	account_name: string | null
	provider: CloudProvider | null
	customer_code: string
	status: CloudScanStatus
	trigger_type: "manual" | "schedule"
	requested_by: string | null
	queued_at: string | null
	started_at: string | null
	completed_at: string | null
	duration_seconds: number | null
	prowler_version: string | null
	counts: CloudScanCounts
	/** Checks that logged an error in a scan that still completed: a missing permission, usually. */
	check_errors: number
	error_code: string | null
	error_message: string | null
	prowler_errors: string[]
	reports: CloudReportKind[]
	findings_pruned: boolean
	/** The account's completed scan before this one, which the new and resolved counts compare with. Null: its first scan. */
	previous_scan_id: number | null
}

export interface CloudCheck {
	check_id: string
	title: string
	service: string
	severity: CloudSeverity
	description: string | null
	risk: string | null
	remediation: string | null
	remediation_urls: string[]
	additional_urls: string[]
	categories: string[]
	compliance: Record<string, string[]>
	passed: number
	failed: number
	manual: number
	muted: number
	status: CloudCheckStatus
}

export interface CloudFinding {
	id: number
	finding_uid: string
	check_id: string
	check_title: string | null
	status: CloudFindingStatus
	severity: CloudSeverity
	muted: boolean
	status_extended: string | null
	service: string
	region: string
	cloud_account_uid: string
	cloud_account_name: string
	resource_uid: string
	resource_name: string
	resource_type: string
	resource_tags: string[]
	detected_at: string | null
	first_seen_at: string | null
	is_new: boolean
}

export interface CloudComplianceFramework {
	key: string
	framework: string | null
	version: string | null
	name: string | null
	description: string | null
	requirements_total: number
	passed: number
	failed: number
	manual: number
	not_assessed: number
}

export interface CloudRequirementCheck {
	check_id: string
	title: string | null
	severity: CloudSeverity | null
	passed: number
	failed: number
	manual: number
	muted: number
	ran: boolean
}

export interface CloudRequirement {
	id: string
	name: string | null
	description: string | null
	section: string | null
	status: CloudRequirementStatus
	checks: CloudRequirementCheck[]
}

export interface CloudAvailability {
	encryption_key_configured: boolean
	runner_configured: boolean
	runner_reachable: boolean
	runner_problem: string | null
	runner_version: string | null
	prowler_version: string | null
	powershell: boolean | null
	providers: CloudProvider[]
}

export interface CloudConnectionTest {
	ok: boolean
	code: string | null
	error_message: string | null
	prowler_error: string | null
	account: CloudAccount
}

export interface CloudFindingsQuery {
	severity?: CloudSeverity[]
	status?: CloudFindingStatus
	check_id?: string
	service?: string
	region?: string
	muted?: boolean
	new?: boolean
	q?: string
	page?: number
	page_size?: number
}

export interface CloudChecksQuery {
	status?: "fail" | "manual" | "pass"
	severity?: CloudSeverity[]
	service?: string
	q?: string
	page?: number
	page_size?: number
}
